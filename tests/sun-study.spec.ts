import { expect, test, type Page } from '@playwright/test'

const harness = '/tests/browser-harness.ts'
async function read(page: Page) {
  return page.evaluate(async url => (await import(/* @vite-ignore */ url)).state(), harness)
}
async function camera(page: Page) {
  return page.evaluate(async url => (await import(/* @vite-ignore */ url)).camera(), harness)
}
async function open(page: Page) {
  await page.goto(process.env.APP_URL ?? 'http://127.0.0.1:5191')
  await page.getByRole('dialog', { name: 'Który projekt chcesz otworzyć?' }).waitFor()
  await page.evaluate(async url => (await import(/* @vite-ignore */ url)).fixture(), harness)
  await page.getByRole('button', { name: '☀ Światło 360°', exact: true }).click()
  await expect(page.getByRole('main', { name: 'Światło 360°' })).toBeVisible()
  await expect(page.locator('canvas')).toBeVisible()
  await page.waitForTimeout(800)
}

test('fixed eye, plan placement, calendar, scrub, playback and return preserve the project', async ({ page }) => {
  await open(page)
  const before = await read(page), eye = await camera(page)
  await page.getByRole('button', { name: 'Spójrz w prawo', exact: true }).click()
  await expect.poll(async () => (await camera(page)).rotation).not.toEqual(eye.rotation)
  expect((await camera(page)).position).toEqual(eye.position)
  const plan = page.getByRole('application', { name: 'Plan domu — wybierz miejsce obserwacji' })
  await plan.focus(); await page.keyboard.press('ArrowRight')
  await expect.poll(async () => (await camera(page)).position).not.toEqual(eye.position)
  await page.getByLabel('Data obserwacji', { exact: true }).fill('2028-02-29')
  await page.getByLabel('Godzina obserwacji', { exact: true }).fill('08:00')
  await expect(page.getByRole('slider', { name: 'Oś czasu dnia' })).toHaveValue('480')
  await page.getByRole('button', { name: 'Godzinę później' }).click()
  await expect(page.getByLabel('Godzina obserwacji', { exact: true })).toHaveValue('09:00')
  await page.getByRole('button', { name: 'Odtwórz dzień' }).click()
  await expect.poll(async () => Number(await page.getByRole('slider', { name: 'Oś czasu dnia' }).inputValue())).toBeGreaterThan(540)
  await page.getByRole('slider', { name: 'Oś czasu dnia' }).focus(); await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button', { name: 'Odtwórz dzień' })).toBeVisible()
  const stopped = await page.getByRole('slider', { name: 'Oś czasu dnia' }).inputValue()
  await page.waitForTimeout(600)
  expect(await page.getByRole('slider', { name: 'Oś czasu dnia' }).inputValue()).toBe(stopped)
  await expect(page.getByLabel('Data obserwacji', { exact: true })).toHaveValue('2028-02-29')
  await page.getByLabel('Godzina obserwacji', { exact: true }).fill('23:58')
  await page.getByLabel('Tempo animacji', { exact: true }).selectOption('4')
  await page.getByRole('button', { name: 'Odtwórz dzień' }).click()
  await expect(page.getByRole('slider', { name: 'Oś czasu dnia' })).toHaveValue('1439')
  await expect(page.getByRole('button', { name: 'Odtwórz dzień' })).toBeVisible()
  expect((await read(page)).project).toEqual(before.project)
  expect((await read(page)).history).toBe(before.history)
  await page.getByRole('button', { name: 'Wróć', exact: true }).click()
  await page.getByRole('button', { name: 'Wnętrze domu', exact: true }).click()
  await page.getByRole('button', { name: '☀ Światło 360°', exact: true }).click()
  await expect(page.getByRole('main', { name: 'Światło 360°' })).toBeVisible()
})

test('phone: plan and bottom timeline stay usable, touch look holds position', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  try {
    await open(page)
    await expect(page.getByRole('application')).toBeHidden()
    await page.getByRole('button', { name: 'Miejsce', exact: true }).tap()
    await expect(page.getByRole('application')).toBeVisible()
    await page.getByRole('button', { name: 'Pokaż symulację', exact: true }).tap()
    await expect(page.getByRole('application')).toBeHidden()
    const before = await camera(page)
    const projection = () => page.evaluate(async () => (await import('/tests/sun-study-harness.ts')).viewProjection())
    const initialProjection = await projection()
    await page.getByRole('slider', { name: 'Szerokość widoku' }).focus()
    await page.keyboard.press('End')
    await expect.poll(async () => (await projection()).fieldOfView).toBe(110)
    expect((await projection()).horizontalScale).toBeLessThan(initialProjection.horizontalScale)
    expect((await camera(page)).position).toEqual(before.position)
    expect((await camera(page)).rotation).toEqual(before.rotation)
    await page.keyboard.press('Home')
    await expect.poll(async () => (await projection()).fieldOfView).toBe(55)
    expect((await projection()).horizontalScale).toBeGreaterThan(initialProjection.horizontalScale)
    expect((await camera(page)).position).toEqual(before.position)
    await page.keyboard.press('End')
    await page.getByRole('button', { name: 'Spójrz w lewo', exact: true }).tap()
    await expect.poll(async () => (await camera(page)).rotation).not.toEqual(before.rotation)
    expect((await camera(page)).position).toEqual(before.position)
    const turned = await camera(page)
    const touch = await context.newCDPSession(page)
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 180, y: 220 }] })
    await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 260, y: 240 }] })
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(async () => (await camera(page)).rotation).not.toEqual(turned.rotation)
    expect((await camera(page)).position).toEqual(before.position)
    await page.getByLabel('Data obserwacji', { exact: true }).fill('2026-12-21')
    await page.getByLabel('Godzina obserwacji', { exact: true }).fill('14:00')
    await page.getByRole('slider', { name: 'Oś czasu dnia' }).tap({ position: { x: 160, y: 12 } })
    expect(await page.getByRole('slider', { name: 'Oś czasu dnia' }).inputValue()).not.toBe('840')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const bounds = await page.getByRole('slider', { name: 'Oś czasu dnia' }).boundingBox()
    expect(bounds!.y + bounds!.height).toBeLessThan(844)
    await page.screenshot({ path: 'output/sun-study-360/mobile.png' })
  } finally { await context.close() }
})

test('actual house: shadows follow time, night disables the sun, floor changes move only the eye', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.APP_URL ?? 'http://127.0.0.1:5191')
  await page.getByRole('dialog', { name: 'Który projekt chcesz otworzyć?' }).waitFor()
  await page.getByRole('dialog').getByRole('button', { name: /^Otwórz projekt/ }).click()
  await expect(page.getByRole('dialog', { name: 'Który projekt chcesz otworzyć?' })).toBeHidden()
  await expect.poll(async () => (await read(page)).project.ref).toBe('project/architekt-7-11')
  const project = (await read(page)).project
  await page.getByRole('button', { name: '☀ Światło 360°', exact: true }).click()
  await page.locator('canvas').waitFor()
  const lighting = () => page.evaluate(async () => (await import('/tests/sun-study-harness.ts')).lighting())
  await page.getByLabel('Data obserwacji', { exact: true }).fill('2026-06-21')
  await page.getByLabel('Godzina obserwacji', { exact: true }).fill('09:00')
  await expect.poll(lighting).not.toBeNull()
  const morning = (await lighting())!
  expect(morning.shadows).toBe(true)
  expect(morning.mapSize).toBeGreaterThanOrEqual(2048)
  const eye = await camera(page)
  await page.getByLabel('Godzina obserwacji', { exact: true }).fill('16:00')
  await expect.poll(async () => (await lighting())!.position).not.toEqual(morning.position)
  expect((await camera(page)).position).toEqual(eye.position)
  await page.getByRole('button', { name: 'Spójrz w prawo', exact: true }).click()
  await page.getByRole('button', { name: 'Spójrz w dół', exact: true }).click()
  await page.screenshot({ path: 'output/sun-study-360/house-afternoon.png' })
  await page.getByLabel('Godzina obserwacji', { exact: true }).fill('00:00')
  await expect.poll(async () => (await lighting())!.intensity).toBe(0)
  await page.getByLabel('Kondygnacja obserwacji', { exact: true }).selectOption({ index: 1 })
  await expect.poll(async () => (await camera(page)).position[1]).toBeGreaterThan(eye.position[1])
  await page.getByLabel('Godzina obserwacji', { exact: true }).fill('14:00')
  await page.screenshot({ path: 'output/sun-study-360/house-upstairs.png' })
  expect((await read(page)).project).toEqual(project)
  expect(errors).toEqual([])
})

test('July kitchen: glass transmits sun, dark fronts retain daylight detail, night stays dark', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  try {
    await page.addInitScript(() => localStorage.setItem('render-quality', 'fast'))
    await page.goto(process.env.APP_URL ?? 'http://127.0.0.1:5191')
    await page.getByRole('button', { name: 'Otwórz projekt: architekt 7.11', exact: true }).click()
    await expect.poll(async () => (await read(page)).project.ref).toBe('project/architekt-7-11')
    const before = (await read(page)).project
    await page.getByRole('button', { name: '☀ Światło 360°', exact: true }).click()
    await page.getByLabel('Data obserwacji', { exact: true }).fill('2026-07-15')
    await page.getByLabel('Godzina obserwacji', { exact: true }).fill('10:56')
    await expect(page.locator('canvas')).toBeVisible()
    await expect.poll(async () => page.evaluate(async () => (await import('/tests/sun-study-harness.ts')).lighting())).not.toBeNull()
    const probe = (compare = false) => page.evaluate(async compare => (await import('/tests/sun-study-harness.ts')).kitchenLighting(compare), compare)
    await expect.poll(async () => (await probe()).environment).toBe(true)
    await expect.poll(async () => (await probe()).floorReady).toBe(true)
    await expect.poll(async () => (await probe(true)).sunlitPixelsThroughGlass).toBeGreaterThan(100)
    const day = await probe(true)
    console.log('July daylight pixels', day)
    expect(day.glassCount).toBeGreaterThan(0)
    expect(day.glassShadows).toBe(0)
    expect(day.opaqueCount).toBeGreaterThan(0)
    expect(day.opaqueShadows).toBe(day.opaqueCount)
    expect(day.interiorLuminance).toBeGreaterThan(25)
    expect(day.interiorLuminance).toBeGreaterThan(day.withoutEnvironment * 1.5)
    expect(day.sunlitPixelsThroughGlass).toBeGreaterThan(100)
    await page.screenshot({ path: 'output/sun-lighting-20261111/kitchen-day.png' })
    await page.getByLabel('Godzina obserwacji', { exact: true }).fill('00:00')
    await expect.poll(async () => (await probe()).environmentIntensity).toBe(0)
    expect((await probe()).interiorLuminance).toBeLessThan(day.interiorLuminance * .25)
    await page.screenshot({ path: 'output/sun-lighting-20261111/kitchen-night.png' })
    await page.getByRole('button', { name: 'Pełna jasność', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Pełna jasność', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.locator('.sun-study-view-label')).toContainText('Pełna jasność · podgląd wnętrza')
    await expect.poll(async () => (await probe()).interiorLuminance).toBeGreaterThan(25)
    await expect(page.getByLabel('Godzina obserwacji', { exact: true })).toHaveValue('00:00')
    await page.screenshot({ path: 'output/sun-controls-20261110/full-brightness-night.png' })
    await page.getByRole('button', { name: 'Pełna jasność', exact: true }).click()
    await expect.poll(async () => (await probe()).interiorLuminance).toBeLessThan(day.interiorLuminance * .25)
    await page.getByLabel('Godzina obserwacji', { exact: true }).fill('10:56')
    await expect.poll(async () => (await probe()).interiorLuminance).toBeGreaterThan(25)
    expect((await read(page)).project).toEqual(before)
    expect(errors).toEqual([])
  } finally { await context.close() }
})

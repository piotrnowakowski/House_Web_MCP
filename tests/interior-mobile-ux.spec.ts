for (const [width, height, view] of [[360, 640, 'Rzut 2D'], [390, 844, 'Wnętrze 3D'], [844, 390, 'Rzut 2D']] as const) test(`inspector ${width} ${view}: room stays visible; save and discard stay reachable`, async ({ page }) => {
  await page.setViewportSize({ width, height })
  await open(page)
  await page.getByRole('button', { name: view, exact: true }).tap()
  const initial = await state(page)
  await page.getByRole('button', { name: 'Edytuj', exact: true }).tap()
  await page.getByRole('button', { name: 'Bathroom', exact: true }).tap()
  await page.waitForTimeout(400)
  const b = initial.project.buildings[0], room = b.spaces.find(r => r.name === 'Bathroom')!
  const corners = room.boundary.map(use => { const w = b.walls.find(w => w.ref === use.wallRef)!; return use.direction === 1 ? w.start : w.end })
  const centre = await point(page, corners.reduce((sum,p) => sum+p.x,0)/corners.length, corners.reduce((sum,p) => sum+p.z,0)/corners.length)
  const sheet = (await page.locator('.adaptive-sheet').boundingBox())!
  expect(centre.y).toBeGreaterThan(116)
  if (height > width) expect(centre.y).toBeLessThan(sheet.y - 8)
  else expect(centre.x).toBeLessThan(sheet.x - 8)
  const field = page.getByRole('spinbutton', { name: 'Szerokość pomieszczenia (m)', exact: true })
  const original = await field.inputValue()
  await field.fill(String(Number(original)+.1))
  await expect(page.getByRole('button', { name: 'Zapisz pomieszczenie', exact: true })).toBeInViewport()
  await page.getByRole('button', { name: 'Odrzuć zmiany', exact: true }).tap()
  await expect(field).toHaveValue(original)
  expect((await state(page)).project).toEqual(initial.project)
  await page.screenshot({ path: `output/interior-mobile-ux/room-${width}.png` })
  await field.fill(String(Number(original)+.1))
  await page.getByRole('button', { name: 'Zapisz pomieszczenie', exact: true }).tap()
  await expect.poll(async () => (await state(page)).history).toBe(initial.history+1)
  expect((await state(page)).project.buildings[0].roof).toEqual(b.roof)
})

test('wall length uses the valid endpoint, previews without saving, and survives undo and reload', async ({ page }) => {
  await open(page)
  const initial = await state(page)
  const hit = await point(page, -3, 3.875, .18)
  await page.touchscreen.tap(hit.x,hit.y)
  await page.getByRole('button', { name: 'Edytuj', exact: true }).tap()
  const anchor = page.getByRole('combobox', { name: 'Punkt stały ściany', exact: true })
  await expect(anchor).toHaveValue('end')
  await expect(anchor.locator('option[value="start"]')).toHaveJSProperty('disabled', true)
  await page.getByRole('spinbutton', { name: 'Długość ściany (m)', exact: true }).fill('3.7')
  await expect(page.locator('.interior-wall-anchor')).toHaveCount(2)
  expect((await state(page)).project).toEqual(initial.project)
  await page.getByRole('button', { name: 'Zapisz zmianę ściany', exact: true }).tap()
  await expect.poll(async () => (await state(page)).history).toBe(initial.history+1)
  const changed = (await state(page)).project
  const wall = changed.buildings[0].walls.find(w => w.ref === 'wall/carport-layout/ground/10')!
  expect(Math.hypot(wall.end.x-wall.start.x,wall.end.z-wall.start.z)).toBeCloseTo(3.7,5)
  expect(wall.end).toEqual(initial.project.buildings[0].walls.find(w => w.ref === wall.ref)!.end)
  expect(changed.buildings[0].roof).toEqual(initial.project.buildings[0].roof)
  await page.screenshot({ path: 'output/interior-mobile-ux/wall-anchor.png' })
  await close(page)
  await page.getByRole('button', { name: 'Cofnij', exact: true }).tap()
  expect((await state(page)).project.buildings).toEqual(initial.project.buildings)
  await page.getByRole('button', { name: 'Ponów', exact: true }).tap()
  await page.waitForTimeout(800)
  await page.reload()
  await page.getByRole('button', { name: 'Otwórz projekt: Główny', exact: true }).tap()
  await expect.poll(async () => (await state(page)).project.ref).toBe(changed.ref)
  expect((await state(page)).project).toEqual(changed)
})

test('overlapping placement stays visible with repair and undo; adding and deleting still work in 2D and 3D', async ({ page }) => {
  await open(page)
  const initial = await state(page)
  await page.getByRole('button', { name: 'Dodaj mebel', exact: true }).tap()
  await page.getByRole('searchbox', { name: 'Szukaj mebli', exact: true }).fill('LACK')
  await page.getByRole('button', { name: 'Umieść LACK Stolik kawowy', exact: true }).tap()
  const location = await point(page,3,-4,.05)
  await page.touchscreen.tap(location.x,location.y)
  await expect.poll(async () => (await state(page)).project.buildings[0].furniture!.length).toBe(initial.project.buildings[0].furniture!.length+1)
  const addedState = (await state(page)).project
  const added = addedState.buildings[0].furniture!.find(i => !initial.project.buildings[0].furniture!.some(j => j.ref===i.ref))!
  await page.getByRole('button', { name: 'Przesuń', exact: true }).tap()
  await drag(page,await point(page,3,-4,.45),await point(page,3,-3,.45))
  const warning = page.getByRole('status', { name: 'Ostrzeżenie ustawienia', exact: true })
  await expect(warning).toBeVisible()
  await expect(warning).toContainText('Zapisano z ostrzeżeniem')
  await expect(warning).toContainText('Nachodzi na:')
  await page.waitForTimeout(3700)
  await expect(warning).toBeVisible()
  await page.screenshot({ path: 'output/interior-mobile-ux/collision.png' })
  await warning.getByRole('button', { name: 'Popraw ustawienie', exact: true }).tap()
  await expect(page.getByRole('button', { name: 'Zastosuj zmiany', exact: true })).toBeInViewport()
  await expect(page.locator('.interior-inspector-form').filter({ has: page.getByRole('heading', { name: added.name, exact: true }) })).not.toContainText('Shift')
  await close(page)
  await warning.getByRole('button', { name: 'Cofnij ruch', exact: true }).tap()
  expect((await state(page)).project.buildings).toEqual(addedState.buildings)
  await page.getByRole('button', { name: 'Wnętrze 3D', exact: true }).tap()
  await page.getByRole('button', { name: 'Więcej', exact: true }).tap()
  await page.getByRole('button', { name: 'Usuń zaznaczenie', exact: true }).tap()
  expect((await state(page)).project.buildings[0].furniture).toEqual(initial.project.buildings[0].furniture)
  await close(page)
  await page.getByRole('button', { name: 'Cofnij', exact: true }).tap()
  expect((await state(page)).project.buildings[0].furniture).toEqual(addedState.buildings[0].furniture)
})

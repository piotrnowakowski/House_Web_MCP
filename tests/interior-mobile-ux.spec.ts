import { test, expect, type Page } from '@playwright/test'

const url = process.env.APP_URL ?? 'http://127.0.0.1:5173'
const state = (page: Page) => page.evaluate(async () => (await import('/tests/browser-harness.ts')).state())
const point = (page: Page, x: number, z: number, y = .1) => page.evaluate(async p => (await import('/tests/browser-harness.ts')).point(p.x, p.z, p.y), { x, z, y })
const close = async (page: Page) => { const button = page.getByRole('button', { name: 'Zamknij panel', exact: true }); if (await button.isVisible()) await button.tap() }
const open = async (page: Page) => {
  await page.goto(url)
  await page.getByRole('button', { name: 'Otwórz projekt: Główny', exact: true }).tap()
  await page.getByRole('button', { name: 'Wnętrze domu', exact: true }).tap()
  await page.getByRole('button', { name: 'Rzut 2D', exact: true }).tap()
  await page.waitForTimeout(600)
}
const drag = async (page: Page, from: { x: number; y: number }, to: { x: number; y: number }, cancel = false) => {
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...from, id: 1 }] })
  for (let i = 1; i <= 12; i++) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: from.x + (to.x - from.x) * i / 12, y: from.y + (to.y - from.y) * i / 12, id: 1 }] })
    await page.waitForTimeout(25)
  }
  await cdp.send('Input.dispatchTouchEvent', { type: cancel ? 'touchCancel' : 'touchEnd', touchPoints: [] })
  await cdp.detach()
  await page.waitForTimeout(250)
}

for (const view of ['Rzut 2D', 'Wnętrze 3D']) test(`${view}: navigation never edits; explicit Move commits once and cancellation preserves geometry`, async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: view, exact: true }).tap()
  const initial = await state(page)
  const stool = initial.project.buildings[0].furniture!.find(i => i.ref === 'interior/reference-stool-one')!
  const start = await point(page, stool.position.x, stool.position.z, stool.heightM)
  await drag(page, start, { x: start.x + 35, y: start.y + 15 })
  expect((await state(page)).project).toEqual(initial.project)
  expect((await state(page)).history).toBe(initial.history)
  await page.getByRole('button', { name: 'Dopasuj widok kondygnacji', exact: true }).tap()
  await page.getByRole('button', { name: 'Edytuj', exact: true }).tap()
  await page.getByRole('button', { name: 'Hoker 1', exact: true }).tap()
  await close(page)
  await page.getByRole('button', { name: 'Przesuń', exact: true }).tap()
  await drag(page, await point(page, stool.position.x, stool.position.z, stool.heightM), await point(page, stool.position.x + .7, stool.position.z, stool.heightM))
  await expect.poll(async () => (await state(page)).history).toBe(initial.history + 1)
  const moved = (await state(page)).project
  expect(moved.buildings[0].furniture!.find(i => i.ref === stool.ref)!.position.x).not.toBe(stool.position.x)
  await expect(page.getByRole('button', { name: 'Anuluj przesuwanie', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Przesuń', exact: true }).tap()
  const current = moved.buildings[0].furniture!.find(i => i.ref === stool.ref)!
  await drag(page, await point(page, current.position.x, current.position.z, current.heightM), await point(page, current.position.x + .5, current.position.z, current.heightM), true)
  expect((await state(page)).project).toEqual(moved)
  await page.getByRole('button', { name: 'Anuluj przesuwanie', exact: true }).tap()
  expect((await state(page)).history).toBe(initial.history + 1)
  await page.getByRole('button', { name: 'Cofnij', exact: true }).tap()
  expect((await state(page)).project.buildings).toEqual(initial.project.buildings)
})

